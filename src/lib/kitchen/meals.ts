export const MEAL_BY_ID: Record<string, MealOption> = Object.fromEntries(
  MEAL_OPTIONS.map((m) => [m.id, m]),
);

export function optionsFor(meal: MealId, group: SwapGroup): MealOption[] {
  return MEAL_OPTIONS.filter((m) => m.group === group && m.slots.includes(meal));
}

export function groupLabel(group: SwapGroup): string {
  switch (group) {
    case "desayuno":
      return "Desayunos";
    case "merienda":
      return "Meriendas";
    case "carne":
      return "Carne magra";
    case "pollo":
      return "Pollo";
    case "pescado":
      return "Pescado";
    case "legumbre":
      return "Legumbres de lata";
    case "huevo":
      return "Huevos";
  }
}
